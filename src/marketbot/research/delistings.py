"""Research 04: what does a USD-M perpetual do after a Binance delisting announcement?

Events: delisting announcements (Binance announcements catalog 161) naming a token whose
USDT perpetual has 5-minute klines in the archive. The entry is the open of the first bar
starting at least 5 minutes after the announcement (time to read and act). The study
reports the move before the entry, and short returns to fixed horizons, without a stop and
with a stop above the entry (a bar touching the stop counts as stopped).
"""

from datetime import timedelta
from pathlib import Path

import numpy as np
import polars as pl

from marketbot.data import announcements, archive
from marketbot.research.feasibility import markdown_table

HORIZONS = {"1h": 12, "4h": 48, "1d": 288, "3d": 864, "7d": 2016}
STOPS = (0.10, 0.20)
DELAY = timedelta(minutes=5)
TAKER = 0.0005
STOP_SLIPPAGE = 0.002


def events(path: Path, since) -> pl.DataFrame:
    frame = pl.read_parquet(path).with_columns(
        symbol=pl.col("title").map_elements(
            announcements.delisted_perpetuals, return_dtype=pl.List(pl.String)
        )
    )
    return (
        frame.explode("symbol")
        .drop_nulls("symbol")
        .filter(pl.col("released") >= since)
        .unique(["symbol", "released"])
        .sort("released")
    )


def study_event(bars: pl.DataFrame, released) -> dict | None:
    times = bars["open_time"]
    start = released + DELAY
    index = int(times.search_sorted(start))
    if index >= bars.height or index < 288:
        return None
    if times[index] - start > timedelta(minutes=10):
        return None  # no trading around the announcement (gap in data)
    opens, highs, closes = (bars[c].to_numpy() for c in ("open", "high", "close"))
    entry = opens[index]
    before = bars.filter(pl.col("open_time") < released)
    row: dict = {
        "pre_24h": float(entry / opens[index - 288] - 1),
        "reaction": float(entry / before["close"][-1] - 1) if before.height else np.nan,
    }
    for name, bars_ahead in HORIZONS.items():
        end = index + bars_ahead - 1
        if end >= len(closes):
            row[f"short {name}"] = np.nan
            for stop in STOPS:
                row[f"short {name} stop {stop:.0%}"] = np.nan
            continue
        row[f"short {name}"] = float(1 - closes[end] / entry - 2 * TAKER)
        for stop in STOPS:
            level = entry * (1 + stop)
            hit = np.nonzero(highs[index : end + 1] >= level)[0]
            if hit.size:
                j = index + int(hit[0])
                exit_price = max(level, opens[j]) * (1 + STOP_SLIPPAGE)
            else:
                exit_price = closes[end]
            row[f"short {name} stop {stop:.0%}"] = float(1 - exit_price / entry - 2 * TAKER)
    return row


def run(root: Path, announcements_path: Path, since) -> tuple[pl.DataFrame, str]:
    rows = []
    for event in events(announcements_path, since).iter_rows(named=True):
        bars = archive.load("klines", [event["symbol"]], root=root, interval="5m").sort("open_time")
        if bars.is_empty():
            continue
        result = study_event(bars, event["released"])
        if result is not None:
            rows.append({"symbol": event["symbol"], "released": event["released"], **result})
    frame = pl.DataFrame(rows)
    columns = [c for c in frame.columns if c.startswith("short")]
    summary = pl.DataFrame(
        {
            "measure": ["pre_24h", "reaction", *columns],
            "events": [int(frame[c].drop_nans().len()) for c in ["pre_24h", "reaction", *columns]],
            "mean %": [
                float(frame[c].drop_nans().mean()) * 100 for c in ["pre_24h", "reaction", *columns]
            ],
            "median %": [
                float(frame[c].drop_nans().median()) * 100
                for c in ["pre_24h", "reaction", *columns]
            ],
            "positive %": [
                float((frame[c].drop_nans() > 0).mean()) * 100
                for c in ["pre_24h", "reaction", *columns]
            ],
        }
    )
    text = "\n".join(
        [
            "# Research 04 results: delisting announcements",
            "",
            "Generated by `uv run mb research delistings`. The analysis is in "
            "[../04-delistings.md](../04-delistings.md).",
            "",
            f"- Events: {frame.height} perpetuals named in Binance delisting announcements "
            f"since {since:%Y-%m-%d} with 5-minute klines around the announcement.",
            f"- Entry: open of the first bar at least {DELAY.seconds // 60} minutes after the "
            "announcement. `pre_24h`: move from 24 hours before the entry; `reaction`: move "
            "from the last close before the announcement to the entry.",
            f"- Short returns after taker fees ({TAKER:.2%} per side); stops fill at the stop "
            f"(or a worse open) plus {STOP_SLIPPAGE:.1%}.",
            "",
            markdown_table(summary, 2),
            "",
        ]
    )
    return frame, text
