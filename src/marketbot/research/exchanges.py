"""Research 14: Binance perpetuals after Bybit and OKX listing and delisting announcements.

Events: Bybit and OKX announcements naming a token whose Binance USDT perpetual (crypto,
not TradFi) had traded for at least a day: spot and perpetual listings, spot and perpetual
delistings. Delistings that follow a Binance delisting announcement for the same token
within 30 days are counted apart ("after Binance"): the Binance perpetual's fate is
already known then, and research 04 covers it. The event study and the funded short model
are research 10's.

Research 17 reruns the study on KuCoin's delistings as a replication. KuCoin delistings that
follow a Bybit or OKX delisting of the same token within 30 days are counted apart ("after
Bybit/OKX"): research 14's strategy would already hold that short.
"""

from datetime import date, datetime, timedelta
from pathlib import Path

import polars as pl

from marketbot.data import announcements, exchanges
from marketbot.research.delistings import DELAY
from marketbot.research.feasibility import markdown_table
from marketbot.research.upbit import perpetual, study_kinds

KINDS = ("spot delisting", "perp delisting", "spot listing", "perp listing")
SHORT_KINDS = ("spot delisting", "perp delisting", "spot listing")
FOLLOW_ON = timedelta(days=30)
NAMES = {"bybit": "Bybit", "okx": "OKX", "kucoin": "KuCoin"}


def event_frame(
    notices: pl.DataFrame,
    binance_delistings: pl.DataFrame,
    since: datetime,
    symbols: set[str],
    venues: tuple[str, ...] = ("bybit", "okx"),
    prior_venues: tuple[str, ...] = (),
) -> pl.DataFrame:
    """Events with the Binance symbol; delistings after Binance's own (or, with
    `prior_venues`, after one of those venues' delistings) get their own kind."""
    delisted: dict[str, list[datetime]] = {}
    for title, released in binance_delistings.select("title", "released").iter_rows():
        for symbol in announcements.delisted_perpetuals(title):
            delisted.setdefault(symbol, []).append(released)
    prior: dict[str, list[datetime]] = {}
    for exchange, title, description, released in (
        notices.filter(pl.col("exchange").is_in(prior_venues))
        .select("exchange", "title", "description", "released")
        .iter_rows()
    ):
        for ticker, kind in exchanges.events(exchange, title, description):
            symbol = perpetual(ticker, symbols)
            if symbol is not None and kind.endswith("delisting"):
                prior.setdefault(symbol, []).append(released)
    rows = []
    recent = notices.filter((pl.col("released") >= since) & pl.col("exchange").is_in(venues)).sort(
        "released"
    )
    for exchange, title, description, released in recent.select(
        "exchange", "title", "description", "released"
    ).iter_rows():
        for ticker, kind in exchanges.events(exchange, title, description):
            symbol = perpetual(ticker, symbols)
            if symbol is None:
                continue
            if kind.endswith("delisting") and any(
                timedelta(0) <= released - binance < FOLLOW_ON
                for binance in delisted.get(symbol, [])
            ):
                kind = f"{kind} after Binance"
            elif kind.endswith("delisting") and any(
                timedelta(0) <= released - earlier < FOLLOW_ON for earlier in prior.get(symbol, [])
            ):
                kind = f"{kind} after Bybit/OKX"
            rows.append(
                {"symbol": symbol, "kind": kind, "exchange": exchange, "released": released}
            )
    return pl.DataFrame(rows).unique(["symbol", "kind", "released"]).sort("released")


def run(
    root: Path,
    notices: pl.DataFrame,
    binance_delistings: pl.DataFrame,
    since: datetime,
    split: date,
    symbols: set[str],
    venues: tuple[str, ...] = ("bybit", "okx"),
    prior_venues: tuple[str, ...] = (),
    heading: str = "# Research 14 results: Binance perpetuals after Bybit and OKX announcements",
    command: str = "uv run mb research exchanges",
    analysis: str = "../14-exchanges.md",
) -> tuple[pl.DataFrame, pl.DataFrame, str]:
    events = event_frame(notices, binance_delistings, since, symbols, venues, prior_venues)
    kinds = (
        *KINDS,
        "spot delisting after Bybit/OKX",
        "perp delisting after Bybit/OKX",
        "spot delisting after Binance",
        "perp delisting after Binance",
    )
    frame, shorts, sections = study_kinds(root, events, kinds, SHORT_KINDS, split)
    counts = (
        events.group_by("kind", "exchange")
        .len()
        .pivot(on="exchange", index="kind", values="len")
        .fill_null(0)
        .sort("kind")
    )
    studied = frame.group_by("kind").len().rename({"len": "studied"})
    counts = counts.join(studied, on="kind", how="left").fill_null(0)
    text = "\n".join(
        [
            heading,
            "",
            f"Generated by `{command}`. The analysis is in [{analysis}]({analysis}).",
            "",
            f"- {' and '.join(NAMES[venue] for venue in venues)} listing and delisting "
            f"announcements since {since:%Y-%m-%d} "
            "naming a token with a Binance crypto USDT perpetual. Studied: those whose "
            "perpetual traded for at least a day before, with 5-minute klines around the "
            "announcement.",
            f"- Delistings within {FOLLOW_ON.days} days after a Binance delisting "
            "announcement for the same token are counted apart (`after Binance`).",
            f"- Entry: open of the first bar at least {DELAY.seconds // 60} minutes after "
            "the announcement; returns after taker fees, no funding in the first tables.",
            f"- Periods split at {split}; t is the mean over its standard error.",
            "",
            markdown_table(counts, 0),
            "",
            *sections,
        ]
    )
    return frame, shorts, text
