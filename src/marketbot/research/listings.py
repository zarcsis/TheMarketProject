"""Research 03: do newly listed USD-M perpetuals drift down after listing?

A listing day is the first day a symbol has daily klines, when that is after the start of
the archive window (so symbols listed before it are not mistaken for new). The study
shorts at the open of day `k` after listing and holds for `h` days with a stop `s` above
entry, checked on daily highs (a day touching the stop counts as stopped, even if it
closed lower; a day opening above the stop fills at the open). Funding is added from the
archive when available: shorts pay when funding is negative.
"""

from dataclasses import dataclass
from datetime import date, timedelta
from pathlib import Path

import numpy as np
import polars as pl

from marketbot.data import archive
from marketbot.research.feasibility import EXCLUDED, markdown_table

TAKER = 0.0005
STOP_SLIPPAGE = 0.002  # new listings are thin; assume a worse stop fill than on majors


@dataclass(frozen=True)
class Variant:
    entry_day: int  # days after the listing day
    hold_days: int
    stop: float  # fraction above entry


VARIANTS = [Variant(k, h, s) for k in (1, 3) for h in (1, 3, 7) for s in (0.15, 0.25, 0.40)]


def listing_days(daily: pl.DataFrame, archive_start: date) -> pl.DataFrame:
    first = daily.group_by("symbol").agg(pl.col("day").min().alias("listed"))
    return first.filter(pl.col("listed") > archive_start + timedelta(days=1))


def simulate_short(days: pl.DataFrame, variant: Variant) -> dict | None:
    """`days`: one symbol's daily bars from the listing day on, sorted."""
    if days.height < variant.entry_day + variant.hold_days:
        return None
    window = days.slice(variant.entry_day, variant.hold_days)
    opens, highs, closes = (window[c].to_numpy() for c in ("open", "high", "close"))
    entry = opens[0]
    stop = entry * (1 + variant.stop)
    exit_price, reason, held = closes[-1], "time", len(opens)
    for i in range(len(opens)):
        if highs[i] >= stop:
            exit_price, reason, held = max(stop, opens[i]) * (1 + STOP_SLIPPAGE), "stop", i + 1
            break
    ret = (entry - exit_price) / entry - TAKER * (entry + exit_price) / entry
    return {
        "symbol": window["symbol"][0],
        "entry_day": window["day"][0],
        "ret": float(ret),
        "r": float(ret / variant.stop),
        "reason": reason,
        "held": held,
        "funding": float(window["funding"][:held].sum()),
    }


def run(root: Path, archive_start: date, split: date) -> tuple[pl.DataFrame, str]:
    klines = archive.load("klines", root=root, interval="1d").filter(
        ~pl.col("symbol").is_in(EXCLUDED)
    )
    daily = klines.select(
        "symbol",
        day=pl.col("open_time").dt.date(),
        open="open",
        high="high",
        close="close",
        quote_volume="quote_volume",
    ).sort("symbol", "day")
    funding = archive.load("fundingRate", root=root)
    if funding.height:
        per_day = funding.group_by("symbol", day=pl.col("calc_time").dt.date()).agg(
            funding=pl.col("last_funding_rate").sum()
        )
        # A short receives positive funding and pays negative funding.
        daily = daily.join(per_day, on=["symbol", "day"], how="left").with_columns(
            pl.col("funding").fill_null(0.0)
        )
    else:
        daily = daily.with_columns(funding=pl.lit(0.0))
    listings = listing_days(daily, archive_start)
    rows = []
    for symbol, listed in listings.iter_rows():
        days = daily.filter((pl.col("symbol") == symbol) & (pl.col("day") >= listed))
        for variant in VARIANTS:
            result = simulate_short(days, variant)
            if result is not None:
                rows.append({**result, **variant.__dict__, "listed": listed})
    trades = pl.DataFrame(rows).with_columns(
        period=pl.when(pl.col("listed") < split)
        .then(pl.lit("first half"))
        .otherwise(pl.lit("second half")),
        ret_with_funding=pl.col("ret") + pl.col("funding"),
    )
    summary = (
        trades.group_by("entry_day", "hold_days", "stop", "period")
        .agg(
            pl.len().alias("trades"),
            (pl.col("ret") > 0).mean().mul(100).alias("win %"),
            pl.col("ret").mean().mul(100).alias("mean %"),
            pl.col("ret").median().mul(100).alias("median %"),
            pl.col("ret_with_funding").mean().mul(100).alias("mean with funding %"),
            (pl.col("reason") == "stop").mean().mul(100).alias("stopped %"),
            (pl.col("ret").mean() / pl.col("ret").std() * pl.len().sqrt()).alias("t"),
        )
        .sort("entry_day", "hold_days", "stop", "period")
    )
    text = "\n".join(
        [
            "# Research 03 results: short new listings",
            "",
            "Generated by `uv run mb research listings`. The analysis is in "
            "[../03-listings.md](../03-listings.md).",
            "",
            f"- Listings: {listings.height} USD-M USDT perpetuals first listed after "
            f"{archive_start} (delisted ones included).",
            f"- Split by listing date at {split}.",
            f"- Costs: taker {TAKER:.2%} per side, stop slippage {STOP_SLIPPAGE:.1%}. "
            "Funding: the sum of the symbol's funding rates over the holding days "
            "(per unit of notional; a short receives positive and pays negative funding).",
            "",
            markdown_table(summary, 2),
            "",
        ]
    )
    return trades, text


def returns_by_age(daily: pl.DataFrame, listings: pl.DataFrame, max_age: int = 30) -> np.ndarray:
    """Mean open-to-close return by days since listing (for the narrative)."""
    joined = daily.join(listings, on="symbol").with_columns(
        age=(pl.col("day") - pl.col("listed")).dt.total_days(),
        ret=pl.col("close") / pl.col("open") - 1,
    )
    return (
        joined.filter(pl.col("age") <= max_age)
        .group_by("age")
        .agg(pl.col("ret").mean())
        .sort("age")["ret"]
        .to_numpy()
    )
